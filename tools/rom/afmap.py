#!/usr/bin/env python3
"""Build the 6D's AF property map from the ROM, not from notes.

Reads three things from qemu/6D/ROM1.BIN:

  * the property dispatch table at 0xF83149DC -- (property id, handler) pairs,
  * the descriptor table at 0xF8B6EB64 -- (id, flags, size, index), 16-byte
    entries,
  * magiclantern/src/property.h for the names ML already uses.

Output: one line per AF property with its handler address and payload size.
"""
import re, struct, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROM = os.path.join(ROOT, "qemu/6D/ROM1.BIN")
PROP_H = os.path.join(ROOT, "magiclantern/src/property.h")
BASE8 = 0xF8000000
DISPATCH = 0xF83149DC
DESCRIPTORS = 0xF8B6EB64


def ml_names():
    names = {}
    for line in open(PROP_H, encoding="utf-8", errors="ignore"):
        m = re.match(r"#define\s+(PROP_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+)", line)
        if m:
            names.setdefault(int(m.group(2), 16), m.group(1))
    return names


def main():
    rom = open(ROM, "rb").read()
    names = ml_names()

    # descriptor sizes: walk both ways from the known entry
    sizes = {}
    for start in (DESCRIPTORS,):
        a = start
        while True:
            off = a - BASE8
            pid, fl, sz, idx = struct.unpack_from("<IIII", rom, off - 16)
            if 0x80050000 <= pid <= 0x8005FFFF and sz < 0x100:
                a -= 16
            else:
                break
        while True:
            off = a - BASE8
            pid, fl, sz, idx = struct.unpack_from("<IIII", rom, off)
            if not (0x80050000 <= pid <= 0x8005FFFF and sz < 0x100):
                break
            sizes[pid] = sz
            a += 16

    # dispatch pairs: (id, handler) with variable spacing, walk window
    pairs = []
    off = DISPATCH - BASE8
    ids = []
    for k in range(0, 0x100, 4):
        w = struct.unpack_from("<I", rom, off + k)[0]
        if 0x80000000 <= w <= 0x8005FFFF:
            ids.append(w)
        elif 0xFF000000 <= w <= 0xFFFFFFFF:
            for i in ids:
                pairs.append((i, w))
            ids = []
        else:
            ids.append(w)

    print("# 6D AF property map, generated by tools/rom/afmap.py")
    print("# property      handler     size  name in ML's property.h")
    for pid, h in pairs:
        print(f"0x{pid:08x}  0x{h:08x}  {sizes.get(pid, '?'):>4}  {names.get(pid, '')}")


if __name__ == "__main__":
    main()
